package com.cgvsu.math;

/**
 * MATH LIBRARY (Артём)
 * -------------------------------------------
 * Реализация двумерного вектора.
 * Используется для работы с экранными координатами и текстурными развертками.
 */

public class Vector2f {
    public float x;
    public float y;

    public Vector2f(float x, float y) {
        this.x = x;
        this.y = y;
    }
}
